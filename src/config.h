#pragma once
// =====================================================================
//  Эмулятор контроллера мотора Fardriver (новый протокол, 16-байтные
//  пакеты 0x80…0xB6) на Arduino Nano — все настройки
// =====================================================================

// ----------------------------- Протокол -------------------------------
#define CFG_BAUD                19200       // 8N1, по дампам Saleae
#define CFG_PACKET_PERIOD_US    28140UL     // период пакетов в потоке (дамп: 28.14 мс, цикл 55 пакетов = 1.548 с)
#define CFG_HELLO_PERIOD_MS     68          // период «AT+VERSION» до рукопожатия (дамп: 68.3 мс)
#define CFG_BOOT_DELAY_MS       400         // «загрузка» контроллера после включения/перезапуска режима
#define CFG_AUTH_REPLY_DELAY_MS 20          // первый пакет данных после рукопожатия (дамп: ~21 мс)
// Через сколько мс без запроса AA 13 … вернуться к AT+VERSION. Реальное поведение НЕ ИЗВЕСТНО
// (в заметках «слать каждые 1000 мс»), 0 = никогда. Учтите полудуплекс SoftwareSerial (см. README).
#ifndef CFG_KEEPALIVE_TIMEOUT_MS
#define CFG_KEEPALIVE_TIMEOUT_MS 0
#endif
// RPM в D6-7 пакета 0x80 = об/мин × это число. Задаётся настройкой контроллера,
// по умолчанию у Fardriver — ×4 (10 об/мин -> 40). Драйвер рассчитан на 4.
#ifndef CFG_RPM_RAW_PER_RPM
#define CFG_RPM_RAW_PER_RPM     4
#endif
#define CFG_THROTTLE_RAW_IDLE   0           // значение D10-11 пакета 0x81 при отпущенном газе
#define CFG_THROTTLE_RAW_FULL   100         // …и при полном газе. Масштаб НЕ подтверждён дампами
#define CFG_SPEED_LEVEL         1           // биты 2-3 байта D0 пакета 0x80 (в дампах всегда 1)

// ----------------------------- Батарея --------------------------------
#define CFG_BATT_CELLS          20          // последовательно, Li-ion NMC (3.0…4.18 В)
#define CFG_BATT_AH             50.0f       // ёмкость, А·ч
#define CFG_BATT_R_MOHM         80.0f       // внутреннее сопротивление сборки + провода, мОм

// ----------------------------- Мотор / колесо -------------------------
#define CFG_MOTOR_KV            12.0f       // об/мин на вольт противо-ЭДС (мотор-колесо)
#define CFG_MOTOR_POLE_PAIRS    16          // пар полюсов (для датчиков Холла)
#define CFG_MOTOR_R_MOHM        25.0f       // сопротивление фазы, мОм
#define CFG_GEAR_RATIO          1.0f        // обороты мотора / обороты колеса (1 — мотор-колесо)
#define CFG_WHEEL_DIAMETER_MM   560         // диаметр колеса, мм (то же значение — в SetWheelDiameter драйвера)

// ----------------------------- Контроллер -----------------------------
#define CFG_PHASE_A_MAX         350.0f      // фазный ток, А
#define CFG_LINE_A_MAX          150.0f      // ток батареи, А
#define CFG_REGEN_PHASE_A       120.0f      // фазный ток рекуперации, А
#define CFG_REGEN_LINE_A        30.0f       // ток рекуперации в батарею, А
#define CFG_FIELD_WEAKEN        1           // ослабление поля (WEAK, бит 6 D0) на высоких оборотах
#define CFG_LOW_SPEED_PCT       50          // ограничение оборотов на передаче Low, % от холостого хода
#define CFG_REV_SPEED_PCT       25          // ограничение оборотов заднего хода, %

// ----------------------------- Защиты ---------------------------------
#define CFG_UV_V                60.0f       // отсечка по низкому напряжению, В (задержка 1 с, возврат +0.5 В);
                                            // за 4 В до порога ток батареи плавно урезается
#define CFG_OV_V                88.0f       // защита от перенапряжения при рекуперации, В
#define CFG_CTRL_DERATE_C       80          // контроллер: начало снижения тока, °C
#define CFG_CTRL_OT_C           95          // контроллер: перегрев (бит 7), возврат на 10 °C ниже
#define CFG_MOTOR_DERATE_C      105         // мотор: начало снижения тока
#define CFG_MOTOR_OT_C          120         // мотор: перегрев (бит 6), возврат на 15 °C ниже

// ----------------------------- Транспорт -------------------------------
#define CFG_MASS_KG             180.0f      // с водителем
#define CFG_CRR                 0.015f      // сопротивление качению
#define CFG_CDA                 0.55f       // аэродинамика Cx·S, м²
#define CFG_ODOMETER_START      313UL       // пробег при включении, 0.1 км (дамп 0A.txt: 0x0139 = 31.3 км)
#define CFG_RANDOM_SEED         20261016UL

// ----------------------------- Железо ---------------------------------
#define PIN_CTRL_RX             6           // сюда TX опрашивающей платы
#define PIN_CTRL_TX             5           // отсюда — в RX опрашивающей платы (5 В! см. README)
#define PIN_BUTTON              3           // кнопка на GND, внутренняя подтяжка
#define PIN_LED                 13          // мигает номером режима
#define CFG_LONG_PRESS_MS       800         // долгое нажатие = перезапуск текущего режима
#define CFG_DEBUG_BAUD          115200      // лог/команды по USB (0 = выключить)
#define CFG_STATUS_PERIOD_MS    1000

#if CFG_RPM_RAW_PER_RPM < 1 || CFG_RPM_RAW_PER_RPM > 8
#error "CFG_RPM_RAW_PER_RPM must be 1..8"
#endif
